package hostsetup

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"log/slog"
	"os/exec"
	"time"

	"github.com/letthemplay/Strata/internal/cli"
	"github.com/letthemplay/Strata/internal/incus"
)

// DefaultSocket is the Incus Unix socket.
const DefaultSocket = "/var/lib/incus/unix.socket"

// requestTimeout bounds one Incus request; creating a pool can take a
// while on large disks.
const requestTimeout = 10 * time.Minute

// Subcommands returns the strata-host subcommands. root is the host's "/".
func Subcommands(root fs.FS) []cli.Subcommand {
	return []cli.Subcommand{{
		Name:    "incus-setup",
		Usage:   "--config FILE [--socket PATH]",
		Summary: "Apply the declared Incus project, agent identity and storage pools",
		Run: func(ctx context.Context, args []string, _, stderr io.Writer) int {
			fset := flag.NewFlagSet("incus-setup", flag.ContinueOnError)
			fset.SetOutput(stderr)
			config := fset.String("config", "", "desired state (JSON, generated by NixOS)")
			socket := fset.String("socket", DefaultSocket, "Incus Unix socket")
			if err := fset.Parse(args); err != nil {
				if errors.Is(err, flag.ErrHelp) {
					return cli.ExitOK
				}
				return cli.ExitUsage
			}
			if *config == "" || fset.NArg() != 0 {
				_, _ = fmt.Fprintln(stderr, "incus-setup: --config is required and no arguments are accepted")
				return cli.ExitUsage
			}
			log := slog.New(slog.NewTextHandler(stderr, nil))
			cfg, err := LoadConfig(*config)
			if err != nil {
				log.ErrorContext(ctx, "invalid configuration", "error", err)
				return cli.ExitError
			}
			client := incus.NewUnix(*socket, "", requestTimeout)
			defer client.Close()
			s := &Setup{Config: cfg, Incus: client, Root: root, Exec: runCommand, Log: log}
			if err := s.Run(ctx); err != nil {
				log.ErrorContext(ctx, "incus setup incomplete", "error", err)
				return cli.ExitError
			}
			log.InfoContext(ctx, "incus setup complete")
			return cli.ExitOK
		},
	}}
}

// runCommand runs a fixed command (no shell) and returns its stdout.
func runCommand(ctx context.Context, name string, args ...string) ([]byte, error) {
	out, err := exec.CommandContext(ctx, name, args...).Output() //nolint:gosec // Fixed commands from this package.
	var exitErr *exec.ExitError
	if errors.As(err, &exitErr) {
		return out, fmt.Errorf("%s: %w: %s", name, err, exitErr.Stderr)
	}
	if err != nil {
		return out, fmt.Errorf("%s: %w", name, err)
	}
	return out, nil
}

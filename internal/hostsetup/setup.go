// Package hostsetup brings Incus on a Strata host to the state declared in
// NixOS: the restricted Strata project, the agent's identity and trust,
// and the storage pools (ADR-0017, ADR-0018).
//
// It runs as root (strata-host incus-setup, started by
// strata-incus-setup.service) and talks to Incus over its Unix socket.
// Nothing else in Strata uses that socket.
//
// Safety rules for storage (ADR-0018):
//   - A pool is created only on devices that are verifiably empty: whole
//     disks, not a system disk, unused, with no partition table, partition
//     or signature. Strata never erases data and never sets source.wipe.
//   - An existing pool is never modified or deleted. A pool that differs
//     from its declaration, or is no longer declared, is reported and left
//     alone; undeclared pools are closed to the Strata project.
package hostsetup

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"log/slog"
	"maps"
	"net/http"
	"net/url"
	"os"
	"slices"
	"strings"

	"github.com/letthemplay/Strata/internal/incus"
)

// NoPoolsSentinel is the pool allow-list of a project when no pool is
// declared: Incus treats an empty list as "all pools", so a name that is
// never a declared pool is used instead. Pool names cannot equal it.
const NoPoolsSentinel = "strata-no-pools"

// Config is the desired state, generated by NixOS.
type Config struct {
	Project            string `json:"project"`
	ProjectDescription string `json:"projectDescription"`
	// ProjectConfig holds the restrictions, features and global limits.
	// Pool access and per-pool limits are added by Run.
	ProjectConfig map[string]string `json:"projectConfig"`
	// Agent is the agent's identity; nil without the agent.
	Agent       *Identity `json:"agent"`
	Pools       []Pool    `json:"pools"`
	DefaultPool string    `json:"defaultPool"`
	// RootSize is the root disk size in the default profile (e.g.
	// "10GiB"), or "". Incus requires a size on instances in pools with a
	// disk limit.
	RootSize string `json:"rootSize"`
	// Networks are the guest networks; DefaultNetwork is eth0 of the
	// default profile ("" for none).
	Networks       []Network `json:"networks"`
	DefaultNetwork string    `json:"defaultNetwork"`
	// ManagementInterface is never a guest uplink.
	ManagementInterface string `json:"managementInterface"`
	// Interfaces maps pinned interface names to their MAC addresses.
	Interfaces map[string]string `json:"interfaces"`
}

// Identity describes the agent's TLS identity and its trust entry.
type Identity struct {
	// Dir holds client.key and client.crt (root only).
	Dir string `json:"dir"`
	// Name is the trust entry's name.
	Name string `json:"name"`
	// CommonName is the certificate's subject CN.
	CommonName string `json:"commonName"`
}

// Pool is a declared storage pool.
type Pool struct {
	Name   string `json:"name"`
	Driver string `json:"driver"` // zfs, lvm or dir
	// Devices are /dev/disk/by-id/ paths (zfs, lvm).
	Devices []string `json:"devices"`
	// Layout is the ZFS vdev layout: "single" or "mirror".
	Layout string `json:"layout"`
	// Path is the mount point of a dir pool; the pool lives in
	// Path/Name.
	Path string `json:"path"`
	// Adopt uses an existing, empty zpool or volume group named like the
	// pool instead of creating one.
	Adopt bool `json:"adopt"`
	// Limit is the project's disk limit on this pool (e.g. "1TiB"), or "".
	Limit string `json:"limit"`
}

// LoadConfig reads a Config from a JSON file.
func LoadConfig(file string) (Config, error) {
	data, err := os.ReadFile(file) //nolint:gosec // Path from the service configuration.
	if err != nil {
		return Config{}, fmt.Errorf("read config: %w", err)
	}
	var c Config
	if err := json.Unmarshal(data, &c); err != nil {
		return Config{}, fmt.Errorf("parse %s: %w", file, err)
	}
	if c.Project == "" || c.Project == "default" {
		return Config{}, fmt.Errorf("%s: invalid project %q", file, c.Project)
	}
	return c, nil
}

// API is the Incus API (incus.Client).
type API interface {
	Do(ctx context.Context, method, path string, body, out any) error
}

// Runner runs a command and returns its standard output.
type Runner func(ctx context.Context, name string, args ...string) ([]byte, error)

// Setup applies a Config.
type Setup struct {
	Config Config
	Incus  API
	// Root is the host's "/" for disk checks.
	Root fs.FS
	// Exec runs LVM queries (pvs).
	Exec Runner
	// Link looks up host interfaces (guest uplinks).
	Link LinkFunc
	Log  *slog.Logger
}

// Run applies the configuration. Failing to set up the project or the
// agent's identity stops it. A refused pool does not stop the others; all
// refusals are returned together.
func (s *Setup) Run(ctx context.Context) error {
	if s.Log == nil {
		s.Log = slog.New(slog.DiscardHandler)
	}
	if err := s.ensureProject(ctx); err != nil {
		return err
	}
	if s.Config.Agent != nil {
		if err := s.ensureIdentity(ctx); err != nil {
			return err
		}
	}
	pinErr := s.checkPins()
	if pinErr != nil {
		s.Log.ErrorContext(ctx, "pinned interface mismatch", "error", pinErr)
	}
	existing, poolErr := s.ensurePools(ctx)
	networks, netErr := s.ensureNetworks(ctx)
	refusals := errors.Join(pinErr, poolErr, netErr)
	if networks == nil {
		networks = map[string]incusNetwork{}
	}
	if err := s.enforceProject(ctx, existing, networks); err != nil {
		return errors.Join(refusals, err)
	}
	moved, err := s.enforceDefaultProfile(ctx, existing, networks)
	if err != nil {
		return errors.Join(refusals, err)
	}
	if moved {
		// The previous default pool or network may no longer be in use:
		// close it now.
		if existing, err = s.listPools(ctx); err == nil {
			if networks, err = s.managedNetworks(ctx); err == nil {
				err = s.enforceProject(ctx, existing, networks)
			}
		}
		if err != nil {
			return errors.Join(refusals, err)
		}
	}
	return refusals
}

// managedNetworks returns the managed networks without changing any.
func (s *Setup) managedNetworks(ctx context.Context) (map[string]incusNetwork, error) {
	all, err := s.listNetworks(ctx)
	if err != nil {
		return nil, err
	}
	maps.DeleteFunc(all, func(_ string, n incusNetwork) bool { return !n.Managed })
	return all, nil
}

// project is the writable part of an Incus project.
type project struct {
	Description string            `json:"description"`
	Config      map[string]string `json:"config"`
}

// ensureProject creates the project if it is missing, with its base
// configuration. Pool access is set by enforceProject afterwards.
func (s *Setup) ensureProject(ctx context.Context) error {
	err := s.Incus.Do(ctx, http.MethodGet, "/1.0/projects/"+url.PathEscape(s.Config.Project), nil, nil)
	if err == nil {
		return nil
	}
	if !incus.IsNotFound(err) {
		return fmt.Errorf("project %s: %w", s.Config.Project, err)
	}
	body := map[string]any{
		"name":        s.Config.Project,
		"description": s.Config.ProjectDescription,
		"config":      s.projectConfig(nil, nil),
	}
	if err := s.Incus.Do(ctx, http.MethodPost, "/1.0/projects", body, nil); err != nil {
		return fmt.Errorf("create project %s: %w", s.Config.Project, err)
	}
	s.Log.InfoContext(ctx, "project created", "project", s.Config.Project)
	return nil
}

// projectConfig returns the full project configuration given the names of
// the pools that exist in Incus (nil before pools are known).
func (s *Setup) projectConfig(existing map[string]storagePool, networks map[string]incusNetwork) map[string]string {
	cfg := maps.Clone(s.Config.ProjectConfig)
	if cfg == nil {
		cfg = map[string]string{}
	}
	declared := make([]string, 0, len(s.Config.Pools))
	limits := map[string]string{}
	for _, p := range s.Config.Pools {
		declared = append(declared, p.Name)
		limits[p.Name] = p.Limit
	}
	// Per-pool limits are only accepted for pools that exist. An undeclared
	// pool is closed to the project, unless the project still uses it:
	// Incus refuses to close a pool under existing instances or volumes,
	// and Strata never deletes them. It stays open until they are gone.
	allowed := declared
	for name, p := range existing {
		limit, isDeclared := limits[name]
		switch {
		case isDeclared && limit != "":
			cfg["limits.disk.pool."+name] = limit
		case isDeclared:
		case p.usedByProject(s.Config.Project):
			allowed = append(allowed, name)
		default:
			cfg["limits.disk.pool."+name] = "0"
		}
	}
	slices.Sort(allowed)
	if len(allowed) == 0 {
		cfg["restricted.storage-pools.access"] = NoPoolsSentinel
	} else {
		cfg["restricted.storage-pools.access"] = strings.Join(allowed, ",")
	}
	cfg["restricted.networks.access"] = s.networkAccess(networks)
	return cfg
}

// enforceProject replaces the project's configuration with the declared
// one, reverting any change made by hand.
func (s *Setup) enforceProject(ctx context.Context, existing map[string]storagePool, networks map[string]incusNetwork) error {
	body := project{Description: s.Config.ProjectDescription, Config: s.projectConfig(existing, networks)}
	if err := s.Incus.Do(ctx, http.MethodPut, "/1.0/projects/"+url.PathEscape(s.Config.Project), body, nil); err != nil {
		return fmt.Errorf("enforce project %s: %w", s.Config.Project, err)
	}
	s.Log.InfoContext(ctx, "project configuration enforced", "project", s.Config.Project,
		"pools", body.Config["restricted.storage-pools.access"], "networks", body.Config["restricted.networks.access"])
	return nil
}

// enforceDefaultProfile puts the root disk of the project's default
// profile on the default pool and its eth0 on the default network, each
// only if declared and existing, and reports whether it changed the
// profile. Other devices and settings of the profile are kept (they are
// subject to the project's restrictions).
func (s *Setup) enforceDefaultProfile(ctx context.Context, existing map[string]storagePool,
	networks map[string]incusNetwork,
) (bool, error) {
	want := map[string]map[string]string{}
	if _, ok := existing[s.Config.DefaultPool]; ok && s.Config.DefaultPool != "" {
		want["root"] = map[string]string{"type": "disk", "path": "/", "pool": s.Config.DefaultPool}
		if s.Config.RootSize != "" {
			want["root"]["size"] = s.Config.RootSize
		}
	}
	if _, ok := networks[s.Config.DefaultNetwork]; ok && s.Config.DefaultNetwork != "" {
		want["eth0"] = map[string]string{"type": "nic", "name": "eth0", "network": s.Config.DefaultNetwork}
	}
	if len(want) == 0 {
		return false, nil // nothing declared, or reported as a pool or network error
	}

	path := "/1.0/profiles/default?project=" + url.QueryEscape(s.Config.Project)
	var p struct {
		Description string                       `json:"description"`
		Config      map[string]string            `json:"config"`
		Devices     map[string]map[string]string `json:"devices"`
	}
	if err := s.Incus.Do(ctx, http.MethodGet, path, nil, &p); err != nil {
		return false, fmt.Errorf("default profile: %w", err)
	}
	if p.Devices == nil {
		p.Devices = map[string]map[string]string{}
	}
	var changed []string
	for name, dev := range want {
		if !maps.Equal(p.Devices[name], dev) {
			p.Devices[name] = dev
			changed = append(changed, name)
		}
	}
	if len(changed) == 0 {
		return false, nil
	}
	if err := s.Incus.Do(ctx, http.MethodPut, path, p, nil); err != nil {
		return false, fmt.Errorf("default profile: %w", err)
	}
	slices.Sort(changed)
	s.Log.InfoContext(ctx, "default profile updated", "devices", strings.Join(changed, ","),
		"pool", s.Config.DefaultPool, "network", s.Config.DefaultNetwork)
	return true, nil
}

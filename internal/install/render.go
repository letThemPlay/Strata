package install

import (
	"fmt"
	"strings"
)

// RenderHostNix renders the host.nix module of the host flake from
// validated answers.
//
// Values are only ever emitted as Nix string literals (see nixString), so
// answer file content cannot become Nix code. The output is nixfmt
// formatted; the golden-file tests and the repository's nix-fmt check
// keep it that way.
func RenderHostNix(a Answers) string {
	var b strings.Builder
	w := func(indent int, format string, args ...any) {
		b.WriteString(strings.Repeat("  ", indent))
		fmt.Fprintf(&b, format, args...)
		b.WriteByte('\n')
	}
	list := func(indent int, name string, items []string) {
		if len(items) == 0 {
			w(indent, "%s = [ ];", name)
			return
		}
		w(indent, "%s = [", name)
		for _, it := range items {
			w(indent+1, "%s", nixString(it))
		}
		w(indent, "];")
	}

	w(0, "# Machine-specific values, generated by strata-install from an answer")
	w(0, "# file (%s). This file is part of the host configuration", APIVersion)
	w(0, "# now; edit it like the rest.")
	w(0, "{")
	w(1, "strata = {")
	w(2, "node.id = %s;", nixString(a.Node.ID))
	b.WriteByte('\n')
	w(2, "access.admin = {")
	w(3, "name = %s;", nixString(a.Admin.Name))
	list(3, "authorizedKeys", a.Admin.AuthorizedKeys)
	w(2, "};")
	b.WriteByte('\n')
	w(2, "disk = {")
	w(3, "device = %s;", nixString(a.Disk.Device))
	w(3, "layout = %s;", nixString(a.Disk.Layout))
	w(2, "};")
	b.WriteByte('\n')
	n := a.Network
	w(2, "networking.management = {")
	w(3, "interface = %s;", nixString(n.Interface))
	w(3, "addressing = %s;", nixString(n.Addressing))
	if n.Addressing == "static" {
		list(3, "addresses", n.Addresses)
		if n.Gateway4 != "" {
			w(3, "gateway4 = %s;", nixString(n.Gateway4))
		}
		if n.Gateway6 != "" {
			w(3, "gateway6 = %s;", nixString(n.Gateway6))
		}
		list(3, "dns", n.DNS)
	}
	w(2, "};")
	w(1, "};")
	w(0, "}")
	return b.String()
}

// nixString returns s as a double-quoted Nix string literal. Backslashes,
// double quotes and the interpolation sequence "${" are escaped, as are
// control characters (which validation rejects anyway).
func nixString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '\\' || c == '"':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '$' && i+1 < len(s) && s[i+1] == '{':
			b.WriteString(`\$`)
		case c == '\n':
			b.WriteString(`\n`)
		case c == '\r':
			b.WriteString(`\r`)
		case c == '\t':
			b.WriteString(`\t`)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}
